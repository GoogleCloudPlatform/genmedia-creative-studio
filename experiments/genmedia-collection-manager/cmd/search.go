var searchCmd = &cobra.Command{
	Use:     "search",
	GroupID: GroupBrowse,
	Short:   "Query documents in a collection by field equality",
	Long: `Searches for documents in the configured Firestore collection where a specified
field (--key) equals a target value (--value). Supports interactive TUI tables,
CSV export, plain text, and JSON output.`,
	Example: `  # Search for all assets created by a specific user
  genmedia search --key="user_email" --value="alice@example.com"

  # Export all records generated by a specific model to CSV
  genmedia search -k="model" -v="imagen-3.0-generate-002" -o=csv > imagen_assets.csv

  # Query documents as JSON with a limit
  genmedia search --key="status" --value="complete" --limit=50 --json`,
	RunE: func(cmd *cobra.Command, args []string) error {
		ctx := cmd.Context()
		client, err := NewFirestoreClient(ctx, projectID, databaseID)
		if err != nil {
			return fmt.Errorf("creating Firestore client: %w", err)
		}
		defer func() { _ = client.Close() }()

		key, _ := cmd.Flags().GetString("key")
		value, _ := cmd.Flags().GetString("value")
		rawView, _ := cmd.Flags().GetString("view")
		limit, _ := cmd.Flags().GetInt("limit")
		view := resolveEffectiveView(cmd, rawView)

		col := client.Collection(collectionName)
		return searchDocs(ctx, col, key, value, view, limit)
	},
}

func init() {
	rootCmd.AddCommand(searchCmd)
	searchCmd.Flags().StringP("key", "k", "", "Document field name to filter on (required)")
	searchCmd.Flags().StringP("value", "v", "", "Field value to match (required)")
	searchCmd.Flags().StringP("view", "o", "table", "Output format: 'table', 'json', 'text', or 'csv'")
	searchCmd.Flags().IntP("limit", "n", 0, "Maximum number of matching documents to return (0 for all)")
	_ = searchCmd.MarkFlagRequired("key")
	_ = searchCmd.MarkFlagRequired("value")
}

type searchResult struct {
	ID        string `json:"id"`
	MimeType  string `json:"mime_type"`
	UserEmail string `json:"user_email"`
	Timestamp string `json:"timestamp"`
	Model     string `json:"model"`
	GCSURI    string `json:"gcsuri,omitempty"`
}

func extractSearchResult(id string, docData map[string]any) searchResult {
	var timestampStr string
	if ts := timeField(docData, "timestamp"); !ts.IsZero() {
		timestampStr = ts.Format(timestampLayout)
	}
	gcsURI := stringField(docData, "gcsuri")
	if gcsURI == "" {
		gcsURI = formatFieldValue(docData["gcs_uris"], 0)
		if gcsURI == "<nil>" {
			gcsURI = ""
		}
	}
	return searchResult{
		ID:        id,
		MimeType:  stringField(docData, "mime_type"),
		UserEmail: stringField(docData, "user_email"),
		Timestamp: timestampStr,
		Model:     stringField(docData, "model"),
		GCSURI:    gcsURI,
	}
}

func searchDocs(ctx context.Context, col *firestore.CollectionRef, key, value, view string, limit int) error {
	iter := col.Where(key, "==", value).Documents(ctx)
	defer iter.Stop()

	var docs []*firestore.DocumentSnapshot
	for {
		doc, err := iter.Next()
		if errors.Is(err, iterator.Done) {
			break
		}
		if err != nil {
			return fmt.Errorf("iterating search results: %w", err)
		}
		docs = append(docs, doc)
	}

	results := make([]searchResult, len(docs))
	for i, doc := range docs {
		results[i] = extractSearchResult(doc.Ref.ID, doc.Data())
	}
	results = applyLimit(results, limit)

	if len(results) == 0 && view != "json" && view != "csv" {
		fmt.Printf("No documents found in collection %q where %q == %q.\n", col.ID, key, value)
		return nil
	}

	switch view {
	case "json":
		return writeJSON(os.Stdout, results)
	case "text":
		for _, res := range results {
			fmt.Printf("ID: %s, MimeType: %s, UserEmail: %s, Timestamp: %s, Model: %s\n",
				res.ID, res.MimeType, res.UserEmail, res.Timestamp, res.Model)
		}
	case "csv":
		headers := []string{"ID", "MIME_TYPE", "USER_EMAIL", "TIMESTAMP", "MODEL", "GCS_URI"}
		rows := make([][]string, len(results))
		for i, res := range results {
			rows[i] = []string{
				res.ID,
				res.MimeType,
				res.UserEmail,
				res.Timestamp,
				res.Model,
				res.GCSURI,
			}
		}
		if err := writeCSV(os.Stdout, headers, rows); err != nil {
			return err
		}
	case "table":
		columns := []table.Column{
			{Title: "ID", Width: 25},
			{Title: "MIME_TYPE", Width: 12},
			{Title: "USER_EMAIL", Width: 25},
			{Title: "TIMESTAMP", Width: 20},
			{Title: "MODEL", Width: 25},
		}

		rows := make([]table.Row, len(results))
		for i, res := range results {
			rows[i] = table.Row{
				res.ID,
				res.MimeType,
				res.UserEmail,
				res.Timestamp,
				res.Model,
			}
		}

		t := newStyledTable(columns, rows, 15)
		vp := viewport.New(120, 30)

		m := model{table: t, viewport: vp, showTable: true, col: col, commandName: "search"}
		if _, err := tea.NewProgram(m).Run(); err != nil {
			return fmt.Errorf("running table view: %w", err)
		}
	default:
		return fmt.Errorf("invalid view format %q: choose \"table\", \"json\", \"text\", or \"csv\"", view)
	}
	return nil
}
